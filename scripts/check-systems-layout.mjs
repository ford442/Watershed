#!/usr/bin/env node
/**
 * CI guard (#371, tightened here): `src/systems/` root holds the store and the
 * thin barrel, nothing else. Everything is a domain folder.
 *
 * Allowed root `*.ts`: GameState.ts (the systems/index.ts barrel had no importers; #465 D)
 * Allowed root `*.tsx`: none. The three deferred React hosts moved —
 * BiomeSystem → biome/, LODManager → lod/, SplashSystem → water/ — and
 * PostProcessing.tsx must not return (deleted in #371). The carve-out that
 * allowed those three is gone on purpose: it was the only thing keeping the
 * rule from being "no root modules", and a permanent exception list is how a
 * layout rule stops being a rule.
 *
 * Also: `src/rendering/index.ts` must not return (#554 F.2). It re-exported ~80
 * names from 12 modules for six importers, so every one of them pulled the whole
 * renderer surface into its module graph; importers name the module instead.
 *
 * Module-size ceiling (#559 C): every `src/**\/*.{ts,tsx}` module is counted in
 * lines. Above MODULE_WARN_LINES it prints a warning and passes; above
 * MODULE_FAIL_LINES it fails unless MODULE_SIZE_ALLOWLIST names it with a
 * reason. Tests are not counted — `*.test.*` / `*.spec.*`, `__tests__/`,
 * `__mocks__/` — nor are `*.d.ts`: a test file's length is its cases, not a
 * module boundary (createRenderer.test.ts is ~1,000 lines of cases). The
 * allowlist is for output that is not a hand-written module (generated
 * validators) or is legitimately one large unit; an entry whose file is gone
 * fails, so the list cannot rot.
 */
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'src');
const systemsDir = join(srcDir, 'systems');

for (const name of ['index.ts', 'index.tsx']) {
  if (existsSync(join(srcDir, 'rendering', name))) {
    console.error(`[systems-layout] src/rendering/${name} is a barrel and was removed (#554 F.2).`);
    console.error("  Import from the module itself, e.g. '../rendering/deriveRendererContextOptions'.");
    process.exit(1);
  }
}

const ALLOWED_ROOT_TS = new Set(['GameState.ts']);

const rootTs = readdirSync(systemsDir).filter((name) => name.endsWith('.ts'));
const banned = rootTs.filter((name) => !ALLOWED_ROOT_TS.has(name));

if (banned.length > 0) {
  console.error('[systems-layout] Root-level src/systems/*.ts must be GameState.ts only.');
  console.error('  Move new modules into a domain folder (journey/, water/, map/, …).');
  console.error('  Banned:');
  for (const name of banned) console.error(`    - ${name}`);
  process.exit(1);
}

const rootTsx = readdirSync(systemsDir).filter((name) => name.endsWith('.tsx'));
if (rootTsx.length > 0) {
  console.error('[systems-layout] Root-level src/systems/*.tsx is not allowed — move it into a domain folder.');
  console.error('  biome/ for biome context, lod/ for LOD, water/ for splash & hydro, …');
  console.error('  Banned:');
  for (const name of rootTsx) console.error(`    - ${name}`);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// Module-size ceiling (#559 C)
// ---------------------------------------------------------------------------

const MODULE_WARN_LINES = 600;
const MODULE_FAIL_LINES = 900;

/** Repo-relative path → why it may exceed MODULE_FAIL_LINES. */
const MODULE_SIZE_ALLOWLIST = new Map([
  [
    'src/formats/level.validate.ts',
    'generated by scripts/compile-validators.mjs (ajv standalone output, one long line); never hand-edited',
  ],
  [
    'src/formats/reach.validate.ts',
    'generated by scripts/compile-validators.mjs (ajv standalone output, one long line); never hand-edited',
  ],
]);

const isCounted = (rel) =>
  /\.tsx?$/.test(rel) &&
  !rel.endsWith('.d.ts') &&
  !/\.(test|spec)\.tsx?$/.test(rel) &&
  !rel.includes('/__tests__/') &&
  !rel.includes('/__mocks__/');

function walk(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full, acc);
    else acc.push(full);
  }
  return acc;
}

const posixRel = (abs) => relative(root, abs).split('\\').join('/');

const lineCount = (text) => {
  if (text.length === 0) return 0;
  const n = text.split('\n').length;
  return text.endsWith('\n') ? n - 1 : n;
};

const sized = walk(srcDir)
  .map(posixRel)
  .filter(isCounted)
  .map((rel) => ({ rel, lines: lineCount(readFileSync(join(root, rel), 'utf8')) }))
  .sort((a, b) => b.lines - a.lines);

const staleAllow = [...MODULE_SIZE_ALLOWLIST.keys()].filter((rel) => !existsSync(join(root, rel)));
if (staleAllow.length > 0) {
  console.error('[systems-layout] Module-size allowlist names files that no longer exist — remove them:');
  for (const rel of staleAllow) console.error(`    - ${rel}`);
  process.exit(1);
}

const oversize = sized.filter(({ rel, lines }) => lines > MODULE_FAIL_LINES && !MODULE_SIZE_ALLOWLIST.has(rel));
if (oversize.length > 0) {
  console.error(`[systems-layout] Modules over ${MODULE_FAIL_LINES} lines (tests excluded) — split them (#559):`);
  console.error('  One file per stage / section / category family; a generated file goes in');
  console.error('  MODULE_SIZE_ALLOWLIST (scripts/check-systems-layout.mjs) with a reason.');
  console.error('  Banned:');
  for (const { rel, lines } of oversize) console.error(`    - ${rel} (${lines} lines)`);
  process.exit(1);
}

const large = sized.filter(
  ({ rel, lines }) => lines > MODULE_WARN_LINES && lines <= MODULE_FAIL_LINES && !MODULE_SIZE_ALLOWLIST.has(rel),
);
if (large.length > 0) {
  console.warn(`[systems-layout] warning: modules over ${MODULE_WARN_LINES} lines (fail above ${MODULE_FAIL_LINES}):`);
  for (const { rel, lines } of large) console.warn(`    - ${rel} (${lines} lines)`);
}

console.log(
  `[systems-layout] ok — root ts: ${rootTs.join(', ') || '(none)'}; root tsx: (none); no rendering barrel; ` +
    `modules: ${sized.length} counted, ${large.length} over ${MODULE_WARN_LINES}, none over ${MODULE_FAIL_LINES} outside the allowlist`,
);
