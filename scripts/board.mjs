#!/usr/bin/env node
/**
 * board.mjs — the open-issue table in docs/reference/BOARD.md, generated from
 * GitHub so the board cannot disagree with the issue list (#574 C).
 *
 *   node scripts/board.mjs            # rewrite the table between the markers
 *   node scripts/board.mjs --check    # exit 1 when the committed table is stale (CI)
 *   node scripts/board.mjs --from issues.json [--check]   # use a saved `gh issue list --json` dump
 *
 * Source: `gh issue list --state open --json number,title,labels --limit 200`.
 * Without a token (`GH_TOKEN` / `GITHUB_TOKEN`) and without `--from`, --check
 * prints why it is skipping and exits 0, so a fork or an offline checkout is
 * not red for want of credentials.
 *
 * The table lives between `<!-- board:issues:start -->` and
 * `<!-- board:issues:end -->`; everything else in BOARD.md (the remainder
 * table, the ratchets) stays hand-written. Status belongs in the issues
 * themselves, not here: the table only carries what GitHub knows.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const BOARD = path.join(ROOT, 'docs', 'reference', 'BOARD.md');
const START = '<!-- board:issues:start -->';
const END = '<!-- board:issues:end -->';

/** "[Opus 5.5 high] P1 Native: one ABI source …" → { priority: 'P1', title: 'Native: one ABI source …' } */
export function parseTitle(raw) {
  let title = raw.replace(/^\s*\[[^\]]*\]\s*/, '').trim();
  const m = title.match(/^(P\d)\b\s*/);
  const priority = m ? m[1] : (title.match(/\bP\d\b/)?.[0] ?? '—');
  if (m) title = title.slice(m[0].length);
  return { priority, title };
}

/** Markdown-table-safe cell text. */
function cell(text) {
  return text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
}

/** The generated block, markers included. Sorted by priority, then number. */
export function renderTable(issues) {
  const rows = issues
    .map((i) => ({ number: i.number, ...parseTitle(i.title), labels: (i.labels ?? []).map((l) => l.name).sort() }))
    .sort((a, b) => (a.priority === b.priority ? a.number - b.number : a.priority < b.priority ? -1 : 1));
  const lines = [
    START,
    '<!-- Generated by `node scripts/board.mjs` from the open issues — do not edit by hand. -->',
    '',
  ];
  if (rows.length === 0) {
    lines.push('_No open issues._');
  } else {
    lines.push('| Issue | Priority | Title | Labels |', '|---|---|---|---|');
    for (const r of rows) {
      lines.push(`| #${r.number} | ${r.priority} | ${cell(r.title)} | ${r.labels.length ? cell(r.labels.join(', ')) : ''} |`);
    }
  }
  lines.push('', END);
  return lines.join('\n');
}

/** BOARD.md with its generated block replaced. Throws when the markers are missing. */
export function spliceBoard(board, table) {
  const a = board.indexOf(START);
  const b = board.indexOf(END);
  if (a < 0 || b < a) throw new Error(`BOARD.md has no ${START} … ${END} block`);
  return board.slice(0, a) + table + board.slice(b + END.length);
}

function loadIssues(fromFile) {
  if (fromFile) return JSON.parse(fs.readFileSync(fromFile, 'utf8'));
  const out = execFileSync(
    'gh',
    ['issue', 'list', '--state', 'open', '--json', 'number,title,labels', '--limit', '200'],
    { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] },
  );
  return JSON.parse(out);
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const fromIdx = args.indexOf('--from');
  const fromFile = fromIdx >= 0 ? args[fromIdx + 1] : null;

  if (!fromFile && !process.env.GH_TOKEN && !process.env.GITHUB_TOKEN) {
    console.log('[board] no GH_TOKEN / GITHUB_TOKEN and no --from: skipping (the issue list needs a token).');
    return;
  }

  const board = fs.readFileSync(BOARD, 'utf8');
  const next = spliceBoard(board, renderTable(loadIssues(fromFile)));
  if (check) {
    if (next !== board) {
      console.error('[board] docs/reference/BOARD.md does not match the open issues. Run `node scripts/board.mjs` and commit.');
      process.exit(1);
    }
    console.log('[board] ok — BOARD.md matches the open issues.');
    return;
  }
  if (next !== board) fs.writeFileSync(BOARD, next);
  console.log(`[board] ${next !== board ? 'updated' : 'unchanged'}: docs/reference/BOARD.md`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
