#!/usr/bin/env node
/**
 * The "Known Working Configuration" table in docs/reference/STARTUP_DIAGNOSTICS.md,
 * generated from `pnpm ls --depth 0` so it cannot drift from the lockfile again
 * (#554 D.2 — it said "React Three Fiber: 9.4.0" for months after the bump).
 *
 *   node scripts/sync-version-table.mjs          rewrite the table in place
 *   node scripts/sync-version-table.mjs --check  exit 1 if the table is stale (CI)
 *
 * Node and pnpm come from package.json (`engines.node`, `packageManager`), not
 * from the running process, so the check gives the same answer on every box.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const docPath = join(repoRoot, 'docs/reference/STARTUP_DIAGNOSTICS.md');
const START = '<!-- versions:start (generated by scripts/sync-version-table.mjs — do not edit) -->';
const END = '<!-- versions:end -->';

/** Rows, in order: label → package name. */
const ROWS = [
  ['React', 'react'],
  ['React DOM', 'react-dom'],
  ['Three.js', 'three'],
  ['React Three Fiber', '@react-three/fiber'],
  ['drei', '@react-three/drei'],
  ['@react-three/rapier', '@react-three/rapier'],
  ['Rapier (rapier3d-compat)', '@dimforge/rapier3d-compat'],
  ['Zustand', 'zustand'],
  ['Vite', 'vite'],
  ['TypeScript', 'typescript'],
];

const pkg = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8'));
const listed = JSON.parse(
  execFileSync('pnpm', ['ls', '--depth', '0', '--json'], { cwd: repoRoot, encoding: 'utf8' }),
)[0];
const installed = { ...listed.dependencies, ...listed.devDependencies };

const lines = [START];
for (const [label, name] of ROWS) {
  const version = installed[name]?.version;
  if (!version) {
    console.error(`[version-table] ${name} is not installed (run pnpm install first).`);
    process.exit(1);
  }
  lines.push(`- **${label}**: ${version}`);
}
lines.push(`- **Node**: ${pkg.engines?.node ?? '(unset)'} (\`engines.node\`)`);
lines.push(`- **pnpm**: ${String(pkg.packageManager ?? '(unset)').replace(/^pnpm@/, '')} (\`packageManager\`)`);
lines.push(END);
const table = lines.join('\n');

const doc = readFileSync(docPath, 'utf8');
const startAt = doc.indexOf(START);
const endAt = doc.indexOf(END);
if (startAt < 0 || endAt < startAt) {
  console.error(`[version-table] markers not found in ${docPath}`);
  process.exit(1);
}
const next = doc.slice(0, startAt) + table + doc.slice(endAt + END.length);

if (process.argv.includes('--check')) {
  if (next !== doc) {
    console.error('[version-table] STARTUP_DIAGNOSTICS.md is stale — run `node scripts/sync-version-table.mjs`.');
    process.exit(1);
  }
  console.log('[version-table] ok');
} else {
  writeFileSync(docPath, next);
  console.log(`[version-table] ${next === doc ? 'unchanged' : 'updated'}`);
}
